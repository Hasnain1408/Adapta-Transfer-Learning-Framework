"""PostgreSQL connection management and schema creation.

Targets a Neon serverless database over ``psycopg2``. Three consequences of
that hosting model shape this module:

- **Neon scales to zero and drops idle connections.** A desktop app sits idle
  for long stretches, so a single long-lived connection *will* be closed out
  from under it. Every statement therefore goes through
  :meth:`Database._execute_with_retry`, which reconnects and retries once when
  the failure is a dropped connection (and never when it is a real SQL error).
- **The first query after an idle period pays a cold-start delay.** Connecting
  is done lazily and can fail, so callers get :class:`DatabaseUnavailable`
  rather than a hard crash — the app stays usable without persistence.
- **TLS is mandatory.** Handled in ``config.resolve_dsn``.

Access is serialised with an ``RLock``: the use case runs on a QThread while
the UI reads on the main thread, and a psycopg2 connection is not thread-safe
for concurrent statements on the same cursor.
"""

from __future__ import annotations

import threading
from contextlib import contextmanager
from typing import Any, Callable, Iterator, Sequence, TypeVar

from .config import DatabaseConfigError, describe_dsn, resolve_dsn

_T = TypeVar("_T")

try:  # pragma: no cover - exercised only when the driver is absent
    import psycopg2
    from psycopg2 import errors as pg_errors
    from psycopg2.extras import RealDictCursor

    PSYCOPG2_AVAILABLE = True
    PSYCOPG2_IMPORT_ERROR: str | None = None
except ImportError as exc:  # pragma: no cover
    psycopg2 = None  # type: ignore[assignment]
    pg_errors = None  # type: ignore[assignment]
    RealDictCursor = None  # type: ignore[assignment]
    PSYCOPG2_AVAILABLE = False
    PSYCOPG2_IMPORT_ERROR = str(exc)


class DatabaseUnavailable(RuntimeError):
    """The database could not be reached or the driver is not installed.

    Distinct from a SQL error: the app catches this to run in a degraded,
    persistence-free mode instead of refusing to start.
    """


#: Executed in order on every start-up. ``IF NOT EXISTS`` throughout, so this
#: doubles as the migration path for an existing database.
#:
#: Notes on the Postgres-specific choices:
#: - ``GENERATED BY DEFAULT AS IDENTITY`` is the modern replacement for
#:   ``SERIAL``; ``BY DEFAULT`` (not ``ALWAYS``) still permits explicit ids,
#:   which matters when importing or seeding rows.
#: - ``TEXT[]`` stores the feature/class name lists natively — psycopg2 maps
#:   those to and from Python lists with no JSON encoding step.
#: - ``TIMESTAMPTZ`` rather than a naive timestamp, so a run recorded in one
#:   timezone still reads correctly in another.
SCHEMA_STATEMENTS: tuple[str, ...] = (
    # ---------------------------------------------------------------- users
    """
    CREATE TABLE IF NOT EXISTS users (
        id            INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name          TEXT        NOT NULL CHECK (length(btrim(name)) > 0),
        email         TEXT        NOT NULL CHECK (length(btrim(email)) > 0),
        password_hash TEXT        NOT NULL DEFAULT '',
        role          TEXT        NOT NULL DEFAULT 'student'
                      CHECK (role IN ('teacher', 'researcher', 'student', 'admin')),
        created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
    )
    """,
    # A database created before authentication existed has a ``users`` table
    # without this column; ``CREATE TABLE IF NOT EXISTS`` above is a no-op
    # against it, so the column is added explicitly. Empty string (not NULL)
    # matches the default above and makes ``verify_password`` fail closed
    # rather than needing a null check of its own.
    "ALTER TABLE users ADD COLUMN IF NOT EXISTS password_hash TEXT NOT NULL DEFAULT ''",
    # Postgres has no SQLite-style ``COLLATE NOCASE``; a unique index on the
    # lowercased column is the standard way to make an email unique
    # case-insensitively without depending on the citext extension.
    "CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower ON users (lower(email))",
    # ------------------------------------------------------------- datasets
    # source_path is UNIQUE so re-running against the same file refreshes the
    # catalogued statistics instead of inserting a near-duplicate row.
    """
    CREATE TABLE IF NOT EXISTS datasets (
        id            INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name          TEXT        NOT NULL,
        file_format   TEXT        NOT NULL
                      CHECK (file_format IN ('.csv', '.xlsx', '.mat')),
        num_samples   INTEGER     NOT NULL DEFAULT 0 CHECK (num_samples  >= 0),
        num_features  INTEGER     NOT NULL DEFAULT 0 CHECK (num_features >= 0),
        feature_names TEXT[]      NOT NULL DEFAULT '{}',
        label_name    TEXT        NOT NULL DEFAULT '',
        num_classes   INTEGER     NOT NULL DEFAULT 0 CHECK (num_classes  >= 0),
        class_names   TEXT[]      NOT NULL DEFAULT '{}',
        source_path   TEXT        NOT NULL UNIQUE,
        created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
    )
    """,
    # A database created before dtype/missing-value tracking existed lacks
    # these columns; ADD COLUMN IF NOT EXISTS backfills them on an existing
    # install the same way password_hash was added to users above.
    "ALTER TABLE datasets ADD COLUMN IF NOT EXISTS dtype_summary TEXT NOT NULL DEFAULT ''",
    "ALTER TABLE datasets ADD COLUMN IF NOT EXISTS missing_value_count INTEGER "
    "NOT NULL DEFAULT 0 CHECK (missing_value_count >= 0)",
    # ---------------------------------------------------------- experiments
    # ON DELETE SET NULL on all three foreign keys: removing a user or a
    # catalogue entry must not destroy the experiment history referencing it.
    # The denormalised source_domain / target_domain columns keep those rows
    # readable after the link is gone.
    """
    CREATE TABLE IF NOT EXISTS experiments (
        id                   INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id              INTEGER     REFERENCES users(id)    ON DELETE SET NULL,
        source_dataset_id    INTEGER     REFERENCES datasets(id) ON DELETE SET NULL,
        target_dataset_id    INTEGER     REFERENCES datasets(id) ON DELETE SET NULL,
        source_domain        TEXT        NOT NULL DEFAULT '',
        target_domain        TEXT        NOT NULL DEFAULT '',
        tl_algorithm         TEXT        NOT NULL,
        classifier           TEXT        NOT NULL DEFAULT '',
        normalization_type   TEXT        NOT NULL DEFAULT 'None',
        standardization_type TEXT        NOT NULL DEFAULT 'None',
        date                 TIMESTAMPTZ NOT NULL DEFAULT now(),
        status               TEXT        NOT NULL DEFAULT 'pending'
                             CHECK (status IN ('pending', 'running', 'completed', 'failed')),
        latent_feature       INTEGER     CHECK (latent_feature IS NULL OR latent_feature > 0),
        regularization_value DOUBLE PRECISION,
        kernel_type          TEXT,
        error_message        TEXT
    )
    """,
    # --------------------------------------------------------- evaluations
    # UNIQUE(experiment_id) enforces the 1:1 with experiments. ON DELETE
    # CASCADE (not SET NULL, unlike the links above) because scores are
    # meaningless once their experiment is gone.
    # "precision" is quoted: it is a keyword in standard SQL.
    """
    CREATE TABLE IF NOT EXISTS evaluations (
        id                  INTEGER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        experiment_id       INTEGER          NOT NULL UNIQUE
                            REFERENCES experiments(id) ON DELETE CASCADE,
        accuracy            DOUBLE PRECISION NOT NULL DEFAULT 0
                            CHECK (accuracy    BETWEEN 0 AND 1),
        "precision"         DOUBLE PRECISION NOT NULL DEFAULT 0
                            CHECK ("precision" BETWEEN 0 AND 1),
        recall              DOUBLE PRECISION NOT NULL DEFAULT 0
                            CHECK (recall      BETWEEN 0 AND 1),
        f1_score            DOUBLE PRECISION NOT NULL DEFAULT 0
                            CHECK (f1_score    BETWEEN 0 AND 1),
        total_samples       INTEGER          NOT NULL DEFAULT 0 CHECK (total_samples       >= 0),
        correct_predictions INTEGER          NOT NULL DEFAULT 0 CHECK (correct_predictions >= 0),
        wrong_predictions   INTEGER          NOT NULL DEFAULT 0 CHECK (wrong_predictions   >= 0)
    )
    """,
    # Added after the fact for the results-comparison module. All nullable:
    # rows recorded before these existed genuinely have no such measurement,
    # and NULL says that where a 0.0 would read as a real reading.
    "ALTER TABLE evaluations ADD COLUMN IF NOT EXISTS auc                DOUBLE PRECISION",
    "ALTER TABLE evaluations ADD COLUMN IF NOT EXISTS mmd_before         DOUBLE PRECISION",
    "ALTER TABLE evaluations ADD COLUMN IF NOT EXISTS mmd_after          DOUBLE PRECISION",
    "ALTER TABLE evaluations ADD COLUMN IF NOT EXISTS alignment_status   TEXT",
    "ALTER TABLE evaluations ADD COLUMN IF NOT EXISTS execution_seconds  DOUBLE PRECISION",
    "ALTER TABLE evaluations ADD COLUMN IF NOT EXISTS adaptation_seconds DOUBLE PRECISION",
    "ALTER TABLE evaluations ADD COLUMN IF NOT EXISTS baseline_accuracy  DOUBLE PRECISION",
    "ALTER TABLE evaluations ADD COLUMN IF NOT EXISTS baseline_f1        DOUBLE PRECISION",
    # ------------------------------------------------------------- indexes
    "CREATE INDEX IF NOT EXISTS idx_experiments_user   ON experiments(user_id)",
    "CREATE INDEX IF NOT EXISTS idx_experiments_date   ON experiments(date DESC)",
    "CREATE INDEX IF NOT EXISTS idx_experiments_status ON experiments(status)",
    "CREATE INDEX IF NOT EXISTS idx_evaluations_exp    ON evaluations(experiment_id)",
)


class Database:
    """Owns the PostgreSQL connection and guarantees the schema exists.

    Construct once at start-up, hand to the repositories, :meth:`close` on
    shutdown. Connecting is lazy — nothing touches the network until the first
    statement — so a slow Neon cold start does not block the window from
    appearing.
    """

    def __init__(self, dsn: str | None = None, *, connect_timeout: int = 10) -> None:
        self._dsn = resolve_dsn(dsn)
        self._connect_timeout = connect_timeout
        self._lock = threading.RLock()
        self._connection: Any = None
        self._schema_ready = False

    # ------------------------------------------------------------------
    @property
    def dsn(self) -> str:
        """The connection string, with the password masked."""
        return describe_dsn(self._dsn)

    @property
    def is_connected(self) -> bool:
        with self._lock:
            return self._connection is not None and self._connection.closed == 0

    # ------------------------------------------------------------------
    def _connect(self) -> Any:
        """Open a fresh connection. Caller must hold the lock."""
        if not PSYCOPG2_AVAILABLE:
            raise DatabaseUnavailable(
                "The psycopg2 driver is not installed.\n\n"
                "Install it with:  pip install psycopg2-binary\n"
                f"(import failed: {PSYCOPG2_IMPORT_ERROR})"
            )
        try:
            connection = psycopg2.connect(
                self._dsn,
                connect_timeout=self._connect_timeout,
                cursor_factory=RealDictCursor,
            )
        except Exception as exc:  # psycopg2.OperationalError and friends
            raise DatabaseUnavailable(
                f"Could not connect to PostgreSQL at {self.dsn}.\n\n{exc}"
            ) from exc

        connection.autocommit = False
        self._connection = connection
        return connection

    def _ensure_connection(self) -> Any:
        """Return a live connection, reconnecting if the old one died."""
        if self._connection is None or self._connection.closed != 0:
            return self._connect()
        return self._connection

    @staticmethod
    def _is_connection_error(exc: Exception) -> bool:
        """Whether *exc* means "the link dropped" rather than "the SQL was bad".

        Only the former is safe to retry: a dropped connection guarantees the
        server rolled the transaction back, so replaying it cannot double-apply
        a write. A constraint violation replayed would just fail again.
        """
        if not PSYCOPG2_AVAILABLE:
            return False
        return isinstance(exc, (psycopg2.OperationalError, psycopg2.InterfaceError))

    def connect(self) -> None:
        """Open the connection and apply the schema. Raises DatabaseUnavailable."""
        with self._lock:
            self._ensure_connection()
            self.create_schema()

    def create_schema(self) -> None:
        """Create every table and index if absent. Safe to call repeatedly.

        Runs as one transaction, so a database is never left half-migrated.
        """

        def operation(cursor: Any) -> None:
            for statement in SCHEMA_STATEMENTS:
                cursor.execute(statement)

        self.run_in_transaction(operation)
        self._schema_ready = True

    # ------------------------------------------------------------------
    def run_in_transaction(self, operation: Callable[[Any], _T]) -> _T:
        """Run *operation(cursor)* in a transaction and return its result.

        Commits on success, rolls back on any exception — so a half-recorded
        experiment (a row without its evaluation) can never reach the database.

        Reconnects and retries the **whole** operation once when the failure is
        a dropped connection, which on Neon is routine rather than exceptional.
        Retrying at this level rather than inside a context manager is
        deliberate and necessary: a ``@contextmanager`` generator may only
        yield once, so re-entering the ``with`` body after an exception has
        been thrown into it raises ``RuntimeError: generator didn't stop after
        throw()``. Taking the operation as a callable lets it simply be called
        again.

        Because the server rolls back an interrupted transaction, replaying it
        cannot double-apply a write.
        """
        with self._lock:
            last_error: Exception | None = None
            for attempt in (1, 2):
                connection = self._ensure_connection()
                cursor = connection.cursor()
                try:
                    result = operation(cursor)
                    connection.commit()
                    return result
                except Exception as exc:
                    try:
                        connection.rollback()
                    except Exception:
                        # Rollback on an already-dead connection is expected.
                        pass
                    if attempt == 1 and self._is_connection_error(exc):
                        self._discard_connection()
                        last_error = exc
                        continue
                    raise
                finally:
                    try:
                        cursor.close()
                    except Exception:
                        pass
            # Both attempts hit a connection error.
            raise DatabaseUnavailable(
                f"Lost the connection to PostgreSQL at {self.dsn}.\n\n{last_error}"
            ) from last_error

    @contextmanager
    def transaction(self) -> Iterator[Any]:
        """Yield a cursor inside a locked transaction.

        Commits on success and rolls back on any exception. Unlike
        :meth:`run_in_transaction` this does **not** retry a dropped
        connection — it cannot, for the generator reason described above. It
        does reconnect *before* yielding, so a connection that died while idle
        is replaced transparently; only one that dies mid-transaction
        surfaces as an error. Prefer :meth:`run_in_transaction` for writes.
        """
        with self._lock:
            connection = self._ensure_connection()
            cursor = connection.cursor()
            try:
                yield cursor
                connection.commit()
            except Exception:
                try:
                    connection.rollback()
                except Exception:
                    pass
                raise
            finally:
                try:
                    cursor.close()
                except Exception:
                    pass

    def _discard_connection(self) -> None:
        """Drop a dead connection so the next call opens a fresh one."""
        if self._connection is not None:
            try:
                self._connection.close()
            except Exception:
                pass
        self._connection = None

    # ------------------------------------------------------------------
    def fetch_all(self, sql: str, params: Sequence[Any] = ()) -> list[dict[str, Any]]:
        """Run a SELECT and return every row as a plain dict."""

        def operation(cursor: Any) -> list[dict[str, Any]]:
            cursor.execute(sql, tuple(params))
            return [dict(row) for row in cursor.fetchall()]

        return self.run_in_transaction(operation)

    def fetch_one(self, sql: str, params: Sequence[Any] = ()) -> dict[str, Any] | None:
        def operation(cursor: Any) -> dict[str, Any] | None:
            cursor.execute(sql, tuple(params))
            row = cursor.fetchone()
            return dict(row) if row is not None else None

        return self.run_in_transaction(operation)

    def execute(self, sql: str, params: Sequence[Any] = ()) -> int:
        """Run a write and return the number of affected rows."""

        def operation(cursor: Any) -> int:
            cursor.execute(sql, tuple(params))
            return cursor.rowcount

        return self.run_in_transaction(operation)

    def execute_returning(
        self, sql: str, params: Sequence[Any] = ()
    ) -> dict[str, Any] | None:
        """Run a write with a ``RETURNING`` clause and hand back that row.

        Postgres' ``RETURNING`` replaces SQLite's ``lastrowid`` and is race
        free — the generated id comes back from the same statement that
        produced it.
        """

        def operation(cursor: Any) -> dict[str, Any] | None:
            cursor.execute(sql, tuple(params))
            row = cursor.fetchone()
            return dict(row) if row is not None else None

        return self.run_in_transaction(operation)

    # ------------------------------------------------------------------
    def table_names(self) -> list[str]:
        """Tables in the current schema, for diagnostics and tests."""
        rows = self.fetch_all(
            "SELECT tablename FROM pg_tables WHERE schemaname = current_schema() "
            "ORDER BY tablename"
        )
        return [row["tablename"] for row in rows]

    def drop_all(self) -> None:
        """Remove every table. Used by the tests; never called by the app."""
        self.execute(
            "DROP TABLE IF EXISTS evaluations, experiments, datasets, users CASCADE"
        )
        self._schema_ready = False

    def close(self) -> None:
        with self._lock:
            self._discard_connection()

    def __enter__(self) -> "Database":
        return self

    def __exit__(self, *_exc_info: object) -> None:
        self.close()


