"""Persisted domain entities representing database records.

These dataclasses correspond to the application database tables (users, datasets,
experiments, evaluations) and serve as the data exchange models across application
and presentation layers.

Distinct from domain.models: models describe execution payloads during active runs,
whereas entities represent durable records that outlive the execution lifecycle.
All entities are immutable and carry an optional integer ID assigned on database insert.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum


class UserRole(str, Enum):
    """User account authorization role."""

    TEACHER = "teacher"
    RESEARCHER = "researcher"
    STUDENT = "student"
    ADMIN = "admin"

    @property
    def label(self) -> str:
        """Title-cased label for display in user interfaces."""
        return self.value.capitalize()

    @classmethod
    def from_value(cls, value: str) -> UserRole:
        """Parse a stored or display string, defaulting to STUDENT for unrecognized values."""
        try:
            return cls(str(value).strip().lower())
        except ValueError:
            return cls.STUDENT


class ExperimentStatus(str, Enum):
    """Lifecycle execution status of an experiment."""

    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"

    @property
    def label(self) -> str:
        """Title-cased status label."""
        return self.value.capitalize()

    @classmethod
    def from_value(cls, value: str) -> ExperimentStatus:
        """Parse a stored status string, defaulting to PENDING on unknown values."""
        try:
            return cls(str(value).strip().lower())
        except ValueError:
            return cls.PENDING


class DatasetFormat(str, Enum):
    """Supported file formats for dataset storage."""

    CSV = ".csv"
    XLSX = ".xlsx"
    MAT = ".mat"

    @classmethod
    def from_path(cls, path: str) -> DatasetFormat:
        """Derive the dataset format from a file path suffix.

        Raises:
            ValueError: If the file extension is not supported.
        """
        from pathlib import Path

        suffix = Path(path).suffix.lower()
        try:
            return cls(suffix)
        except ValueError as exc:
            supported = ", ".join(member.value for member in cls)
            raise ValueError(
                f"Unsupported dataset format {suffix!r}. Supported: {supported}"
            ) from exc


@dataclass(frozen=True)
class User:
    """User account entity representing a researcher or student owning experiments."""

    name: str
    email: str
    role: UserRole = UserRole.STUDENT
    # PBKDF2 hash generated by domain.auth.hash_password; never plaintext.
    password_hash: str = ""
    id: int | None = None
    created_at: datetime | None = None

    @property
    def display_name(self) -> str:
        """User name formatted with role annotation."""
        return f"{self.name} ({self.role.label})"


@dataclass(frozen=True)
class DatasetRecord:
    """Catalogued metadata record for a dataset file."""

    name: str
    file_format: DatasetFormat
    num_samples: int
    num_features: int
    label_name: str = ""
    num_classes: int = 0
    feature_names: list[str] = field(default_factory=list)
    class_names: list[str] = field(default_factory=list)
    # Compact summary of feature column data types, such as float64 x24, int64 x2.
    dtype_summary: str = ""
    # Count of missing or non-numeric feature entries imputed during loading.
    missing_value_count: int = 0
    source_path: str = ""
    id: int | None = None
    created_at: datetime | None = None


@dataclass(frozen=True)
class ExperimentRecord:
    """Configured transfer learning experiment execution record."""

    tl_algorithm: str
    classifier: str
    source_domain: str
    target_domain: str
    date: datetime
    status: ExperimentStatus = ExperimentStatus.PENDING
    normalization_type: str = "None"
    standardization_type: str = "None"
    latent_feature: int | None = None
    regularization_value: float | None = None
    kernel_type: str | None = None
    user_id: int | None = None
    source_dataset_id: int | None = None
    target_dataset_id: int | None = None
    error_message: str | None = None
    id: int | None = None


@dataclass(frozen=True)
class EvaluationRecord:
    """Classification performance metrics and alignment diagnostics for an experiment."""

    experiment_id: int
    accuracy: float
    precision: float
    recall: float
    f1_score: float
    total_samples: int = 0
    correct_predictions: int = 0
    wrong_predictions: int = 0
    # Optional diagnostic metrics (nullable for runs where not recorded).
    auc: float | None = None
    mmd_before: float | None = None
    mmd_after: float | None = None
    alignment_status: str | None = None
    execution_seconds: float | None = None
    adaptation_seconds: float | None = None
    baseline_accuracy: float | None = None
    baseline_f1: float | None = None
    overlap_before: float | None = None
    overlap_after: float | None = None
    id: int | None = None

    @property
    def mmd_change_percent(self) -> float | None:
        """Percentage change in MMD: ((before - after) / before) * 100."""
        if self.mmd_before is None or self.mmd_after is None:
            return None
        if abs(self.mmd_before) < 1e-12:
            return 0.0
        return (self.mmd_before - self.mmd_after) / self.mmd_before * 100.0

    @property
    def overlap_change_points(self) -> float | None:
        """Change in domain overlap measured in percentage points (after - before)."""
        if self.overlap_before is None or self.overlap_after is None:
            return None
        return self.overlap_after - self.overlap_before

    @property
    def accuracy_delta(self) -> float | None:
        """Accuracy improvement over no-adaptation baseline (adapted - baseline)."""
        if self.baseline_accuracy is None:
            return None
        return self.accuracy - self.baseline_accuracy

    @property
    def f1_delta(self) -> float | None:
        """F1-score improvement over no-adaptation baseline (adapted - baseline)."""
        if self.baseline_f1 is None:
            return None
        return self.f1_score - self.baseline_f1


@dataclass(frozen=True)
class ExperimentHistoryEntry:
    """Aggregated read model joining an experiment with its owner and evaluation metrics."""

    experiment: ExperimentRecord
    user: User | None = None
    evaluation: EvaluationRecord | None = None
